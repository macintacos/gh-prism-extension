#!/usr/bin/env bash
# Creates a private sandbox repository with three open PRs (small, large, and
# complicated) for surveying GitHub's Files changed tab. All content is fake.
# Resumable per PR: the repo, main, and each PR are skipped when they already exist.
# A run that fails partway through a PR leaves that PR for you to fix by hand.
#
# Usage: scripts/create-sandbox.sh <owner>/<repo>
set -euo pipefail

readonly repo="${1:?usage: scripts/create-sandbox.sh <owner>/<repo>}"

commit() {
	git add -A
	git commit -q -m "$1"
}

edit() {
	SUB="$2" perl -0777 -pi -e "$2"' or die "no match for $ENV{SUB} in $ARGV\n"' "$1"
}

pr_exists() {
	gh pr view "$1" -R "$repo" >/dev/null 2>&1
}

open_pr() {
	git push -q -u --force-with-lease origin "$1"
	gh pr create -R "$repo" --base main --head "$1" --title "$2" --body "$3"
}

seed_main() {
	git ls-remote --exit-code origin main >/dev/null 2>&1 && return
	git checkout -q -B main
	mkdir -p config docs tests src/generated

	cat >README.md <<'EOF'
# prism-fixture

A fake crate that exists only to stage pull request scenarios.

It parses lines, keeps a few, and renders them as a list.
EOF

	cat >Cargo.toml <<'EOF'
[package]
name = "prism-fixture"
version = "0.1.0"
edition = "2021"

[dependencies]
EOF

	cat >Cargo.lock <<'EOF'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "prism-fixture"
version = "0.1.0"
EOF

	echo 'src/generated/** linguist-generated=true' >.gitattributes

	cat >config/app.toml <<'EOF'
[engine]
limit = 10
timeout_ms = 500

[render]
bullet = "-"
EOF

	cat >docs/guide.md <<'EOF'
# Guide

Create an engine with a limit, then call `run` on some text.
The engine keeps the first lines up to the limit and drops the rest.

Pass the result to `render` to get a bulleted list.
EOF

	cat >tests/integration.rs <<'EOF'
use prism_fixture::engine::Engine;

#[test]
fn keeps_up_to_limit() {
    let engine = Engine::new(2);
    assert_eq!(engine.run("a\nb\nc").len(), 2);
}
EOF

	cat >src/lib.rs <<'EOF'
pub mod engine;
pub mod notes;
pub mod parser;
pub mod render;

pub fn version() -> &'static str {
    "0.1.0"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reports_version() {
        assert_eq!(version(), "0.1.0");
    }
}
EOF

	cat >src/engine.rs <<'EOF'
use crate::parser::parse;

pub struct Engine {
    limit: usize,
}

impl Engine {
    pub fn new(limit: usize) -> Self {
        Self { limit }
    }

    pub fn run(&self, input: &str) -> Vec<String> {
        let items = parse(input);
        items.into_iter().take(self.limit).collect()
    }

    pub fn limit(&self) -> usize {
        self.limit
    }
}
EOF

	cat >src/parser.rs <<'EOF'
/// Splits input into trimmed, non-empty lines.
///
/// Blank lines are dropped.
pub fn parse(input: &str) -> Vec<String> {
    input
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .map(String::from)
        .collect()
}
EOF

	cat >src/render.rs <<'EOF'
/// Renders items as a bulleted list.
pub fn render(items: &[String]) -> String {
    items
        .iter()
        .map(|item| format!("- {item}"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Renders a heading line.
pub fn heading(text: &str) -> String {
    format!("# {text}")
}

/// Renders a horizontal rule.
pub fn rule() -> String {
    String::from("---")
}

/// Renders a blank separator.
pub fn blank() -> String {
    String::new()
}

/// Renders a count summary.
pub fn summary(count: usize) -> String {
    format!("{count} items")
}
EOF

	cat >src/notes.rs <<'EOF'
/*
Design notes for the fixture engine.
The engine reads text and splits it into lines.
Each line is trimmed before anything else happens.
Empty lines never reach the limit check.
The limit counts kept lines, not input lines.
Rendering happens after the limit is applied.
The renderer only knows about bullets and headings.
Headings use a single hash and a space.
Bullets use a dash unless config says otherwise.
Config is read once at startup.
A timeout guards slow inputs.
The timeout is measured in milliseconds.
Generated schema code lives in its own folder.
Nobody edits generated code by hand.
Helpers stay small and have no state.
Tests live both inline and in the tests folder.
Inline tests cover private helpers.
Integration tests cover the public engine.
The lockfile pins every dependency.
Docs describe behaviour, not internals.
The guide is the entry point for new readers.
Notes like these are for maintainers.
They change rarely and stay in prose.
Nothing here is real; it stages review scenarios.
Line wrapping in these notes is deliberate.
Each sentence sits on its own line.
That keeps diffs of this comment narrow.
End of design notes.
*/

pub const NOTES_VERSION: u32 = 1;
EOF

	cat >src/util.rs <<'EOF'
pub fn clamp(value: usize, max: usize) -> usize {
    if value > max {
        max
    } else {
        value
    }
}

pub fn is_blank(text: &str) -> bool {
    text.trim().is_empty()
}

pub fn first_word(text: &str) -> &str {
    text.split_whitespace().next().unwrap_or("")
}
EOF

	cat >src/generated/schema.rs <<'EOF'
// @generated by fixture-schema. Do not edit.
pub struct Schema {
    pub name: &'static str,
    pub version: u32,
}

pub const SCHEMA: Schema = Schema {
    name: "prism",
    version: 1,
};
EOF

	commit "Seed the fixture crate"
	git push -q -u origin main
}

small_pr() {
	pr_exists small-change && return
	git checkout -q -B small-change main
	edit src/engine.rs 's/take\(self\.limit\)/take(self.limit.max(1))/'
	edit docs/guide.md 's/drops the rest/ignores the rest/'
	commit "Keep at least one line"
	local url
	url=$(open_pr small-change "Keep at least one line" "A zero limit dropped every line; keep at least one.")
	gh pr review "${url##*/}" -R "$repo" --comment --body "Could the guide say what happens with a zero limit?"
	edit docs/guide.md 's/^The engine keeps.*\K/\nA zero limit still keeps the first line./m'
	commit "Document the zero-limit case"
	git push -q
}

module_file() {
	awk -v n="$1" 'BEGIN {
		printf "export const id = \"module-%s\";\n\n", n
		for (i = 1; i <= 12; i++) {
			printf "export function step%d(input: number): number {\n", i
			printf "  return input + %d;\n}\n\n", i
		}
		printf "export const steps = 12;\n"
	}'
}

large_pr() {
	pr_exists large-change && return
	git checkout -q -B large-change main
	mkdir -p web/src/modules web/src/data web/public
	local n
	for n in $(seq -w 1 150); do
		module_file "$n" >"web/src/modules/module-$n.ts"
	done
	{
		echo 'export const catalog = ['
		# 3,000 lines with the brackets.
		seq 1 2998 | awk '{ printf "  { id: %d, name: \"item-%d\" },\n", $1, $1 }'
		echo '];'
	} >web/src/data/catalog.ts
	base64 -d >web/public/logo.png <<'EOF'
iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==
EOF
	commit "Add the web module catalog"
	open_pr large-change "Add the web module catalog" "Adds 150 modules, a large catalog, and a logo." >/dev/null
}

complicated_pr() {
	pr_exists complicated-change && return
	git checkout -q -B complicated-change main

	edit src/engine.rs 's/        self\.limit\n    \}\n\K/\n    pub fn reset(&mut self, limit: usize) {\n        self.limit = limit;\n    }\n/'
	echo 'fixture-color = "1.2"' >>Cargo.toml
	cat >Cargo.lock <<'EOF'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "fixture-color"
version = "1.2.0"

[[package]]
name = "prism-fixture"
version = "0.1.0"
dependencies = [
 "fixture-color",
]
EOF
	edit config/app.toml 's/timeout_ms = 500/timeout_ms = 750/'
	edit src/generated/schema.rs 's/version: 1,/version: 2,/'
	edit src/generated/schema.rs 's/pub version: u32,\K/\n    pub strict: bool,/'
	edit src/generated/schema.rs 's/    version: 2,\K/\n    strict: true,/'
	commit "Add engine reset and strict schema"

	# Only lines inside mod tests change, so the whole lib.rs diff is test code.
	edit src/lib.rs 's/^(?=    fn reports_version\(\) \{\n)/    fn version_is_semver() {\n        assert_eq!(version().split(".").count(), 3);\n    }\n\n    #[test]\n/m'
	cat >>tests/integration.rs <<'EOF'

#[test]
fn reset_changes_limit() {
    let mut engine = Engine::new(1);
    engine.reset(3);
    assert_eq!(engine.limit(), 3);
}
EOF
	git mv src/util.rs src/helpers.rs
	edit src/helpers.rs 's/unwrap_or\(""\)/unwrap_or_default()/'
	commit "Test reset and rename util to helpers"

	edit README.md 's/keeps a few/keeps up to a limit/'
	edit docs/guide.md 's/to get a bulleted list/to get a bulleted list, one item per line/'
	# Only /// lines change.
	edit src/parser.rs 's/Blank lines are dropped\./Blank and whitespace-only lines are dropped./'
	# These edits sit 10+ lines apart so code and docstring stay separate hunks.
	edit src/render.rs 's/"- \{item\}"/"* {item}"/'
	edit src/render.rs 's/Renders a count summary\./Renders a count summary such as "3 items"./'
	# These edits sit 20+ lines apart so the second hunk opens inside the block comment.
	edit src/notes.rs 's/^Each line is trimmed before anything else happens\./Each line is trimmed of surrounding whitespace first./m'
	edit src/notes.rs 's/^Each sentence sits on its own line\./Every sentence sits on a line of its own./m'
	commit "Polish docs and comments"

	local url line
	url=$(open_pr complicated-change "Engine reset, strict schema, and docs" "Three commits mixing code, tests, a rename, generated code, and docs.")
	line=$(grep -n 'self.limit = limit;' src/engine.rs | cut -d: -f1)
	gh api "repos/$repo/pulls/${url##*/}/comments" \
		-f body="Should reset reject a zero limit?" \
		-f commit_id="$(git rev-parse HEAD)" \
		-f path=src/engine.rs -F line="$line" -f side=RIGHT >/dev/null
}

gh repo view "$repo" >/dev/null 2>&1 ||
	gh repo create "$repo" --private --description "Fake fixture repo for gh-prism PR UI scenarios"

clone_dir=$(mktemp -d)
gh repo clone "$repo" "$clone_dir" -- -q
cd "$clone_dir"

# Call order fixes the PR numbers (#1 small, #2 large, #3 complicated) that Linear cites.
seed_main
small_pr
large_pr
complicated_pr

for branch in small-change large-change complicated-change; do
	gh pr view "$branch" -R "$repo" --json url --jq .url
done
